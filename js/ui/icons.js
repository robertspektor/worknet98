const GLYPHS = Object.freeze({
  minimize: ['........', '........', '........', '........', '........', '.kkkkkk.', '.kkkkkk.'],
  close: ['kk....kk', '.kk..kk.', '..kkkk..', '...kk...', '..kkkk..', '.kk..kk.', 'kk....kk'],
});

function pixelRuns(row) {
  const runs = [];
  [...row].forEach((color, x) => {
    if (color === '.') return;
    const last = runs.at(-1);
    if (last && last.color === color && last.x + last.width === x) {
      last.width += 1;
    } else {
      runs.push({ color, x, width: 1 });
    }
  });
  return runs;
}

function pixelSvg(rows, width, height) {
  const rects = rows.flatMap((row, y) => pixelRuns(row).map(run =>
    `<rect x="${run.x}" y="${y}" width="${run.width}" height="1" fill="${PALETTE[run.color]}"/>`));
  const viewWidth = rows[0].length;

  return `<svg class="pixel-icon" width="${width}" height="${height}" viewBox="0 0 ${viewWidth} ${rows.length}" shape-rendering="crispEdges" aria-hidden="true">${rects.join('')}</svg>`;
}

export function iconSvg(name, size = 32) {
  return pixelSvg(ICONS[name] ?? ICONS.program, size, size);
}

export function glyphSvg(name) {
  return pixelSvg(GLYPHS[name], 8, 7);
}
